//! Typed external addresses and a shared native/browser URI codec.

use std::collections::BTreeMap;
use std::fmt::Display;
use std::str::FromStr;

use percent_encoding::{NON_ALPHANUMERIC, percent_decode_str, utf8_percent_encode};
use serde::{Deserialize, Serialize};

/// A stable route key and complete, owned parameters.
#[derive(Clone, Debug, PartialEq, Eq, Serialize, Deserialize)]
pub struct RouteAddress {
    /// Stable external route key, independent of the Rust variant's name.
    pub route: String,
    /// Formatted parameter values. Optional query parameters may be absent.
    pub params: BTreeMap<String, String>,
}

/// One parameter's external schema.
#[derive(Clone, Copy, Debug, Serialize)]
pub struct ParameterDescriptor {
    /// Stable field or path-placeholder name.
    pub name: &'static str,
    /// Rust parameter type; parsing is performed by its `RouteParam` implementation.
    pub value_type: &'static str,
    /// Whether decoding requires this parameter.
    pub required: bool,
}

/// A discoverable route mapping generated by `#[derive(rake::Route)]`.
#[derive(Clone, Copy, Debug, Serialize)]
pub struct RouteDescriptor {
    /// Stable external route key.
    pub id: &'static str,
    /// Absolute path template with named `{parameters}`.
    pub path: &'static str,
    /// All path and query parameters. Fields absent from the path are query parameters.
    pub params: &'static [ParameterDescriptor],
}

/// Parsing/formatting for domain IDs and ordinary scalar route parameters.
pub trait RouteParam: Sized {
    /// Parses one decoded string into the domain type.
    ///
    /// # Errors
    /// Returns an application-readable reason when the decoded value is invalid.
    fn parse_param(value: &str) -> Result<Self, String>;

    /// Formats one canonical parameter value.
    fn format_param(&self) -> String;
}

impl<T: FromStr + Display> RouteParam for T
where
    T::Err: Display,
{
    fn parse_param(value: &str) -> Result<Self, String> {
        value.parse().map_err(|error: T::Err| error.to_string())
    }

    fn format_param(&self) -> String {
        self.to_string()
    }
}

/// A compact typed destination. Neither this trait nor its parameters require `Send`.
pub trait Route: Clone + 'static {
    /// Returns the canonical external key and formatted parameters.
    fn encode(&self) -> RouteAddress;

    /// Validates an owned address, including missing, unknown and malformed parameters.
    ///
    /// # Errors
    /// Returns [`RouteDecodeError`] for unknown routes, missing/unknown parameters
    /// or values rejected by their [`RouteParam`] implementation.
    fn decode(address: &RouteAddress) -> Result<Self, RouteDecodeError>;

    /// Describes the complete closed route registry.
    fn descriptors() -> &'static [RouteDescriptor];

    /// Encodes this destination as an absolute path and optional query string.
    ///
    /// # Errors
    /// Returns [`RouteDecodeError`] for invalid addresses or destinations that do
    /// not round-trip through the registered URI patterns.
    fn to_uri(&self) -> Result<String, RouteDecodeError> {
        let address = self.encode();
        let uri = address_uri(&address, Self::descriptors())?;
        let decoded = Self::decode(&uri_address(&uri, Self::descriptors())?)?;

        if decoded.encode() != address {
            return Err(RouteDecodeError::InvalidUri(
                "destination is shadowed by another route pattern".into(),
            ));
        }

        Ok(uri)
    }

    /// Decodes a path/query URI using the same contract as the browser adapter.
    ///
    /// # Errors
    /// Returns [`RouteDecodeError`] for malformed or ambiguous URIs, unknown routes
    /// or parameters that fail destination decoding.
    fn from_uri(uri: &str) -> Result<Self, RouteDecodeError> {
        Self::decode(&uri_address(uri, Self::descriptors())?)
    }
}

/// A root-only application has no typed routing destinations.
#[derive(Clone)]
pub enum NoRoute {}

impl Route for NoRoute {
    fn encode(&self) -> RouteAddress {
        match *self {}
    }

    fn decode(address: &RouteAddress) -> Result<Self, RouteDecodeError> {
        Err(RouteDecodeError::UnknownRoute(address.route.clone()))
    }

    fn descriptors() -> &'static [RouteDescriptor] {
        &[]
    }
}

/// An inspectable address/URI failure.
#[derive(Clone, Debug, PartialEq, Eq, thiserror::Error, Serialize, Deserialize)]
pub enum RouteDecodeError {
    /// No registered external key or path matched.
    #[error("unknown route: {0}")]
    UnknownRoute(String),
    /// A required parameter was absent.
    #[error("missing route parameter: {0}")]
    MissingParameter(String),
    /// Extra parameters are rejected instead of silently ignored.
    #[error("unknown route parameter: {0}")]
    UnknownParameter(String),
    /// A parameter appeared more than once in a URI.
    #[error("duplicate route parameter: {0}")]
    DuplicateParameter(String),
    /// The domain parser rejected a value.
    #[error("invalid route parameter {name}: {reason}")]
    InvalidParameter {
        /// Parameter name.
        name: String,
        /// Parser's reason, without reflecting the untrusted value automatically.
        reason: String,
    },
    /// Invalid percent encoding, UTF-8, URI shape or ambiguous path value.
    #[error("invalid route URI: {0}")]
    InvalidUri(String),
}

impl RouteAddress {
    /// Checks parameter names and presence against the selected route descriptor.
    ///
    /// # Errors
    /// Returns [`RouteDecodeError`] when supplied parameter names do not match
    /// the descriptor, or a required parameter is missing.
    pub fn validate(&self, descriptor: &RouteDescriptor) -> Result<(), RouteDecodeError> {
        for key in self.params.keys() {
            if !descriptor.params.iter().any(|param| param.name == key) {
                return Err(RouteDecodeError::UnknownParameter(key.clone()));
            }
        }

        for param in descriptor.params {
            if param.required && !self.params.contains_key(param.name) {
                return Err(RouteDecodeError::MissingParameter(param.name.into()));
            }
        }

        Ok(())
    }

    /// Parses a required parameter through its domain contract.
    ///
    /// # Errors
    /// Returns [`RouteDecodeError::MissingParameter`] for absent values, or
    /// [`RouteDecodeError::InvalidParameter`] if parsing fails.
    pub fn parameter<T: RouteParam>(&self, name: &str) -> Result<T, RouteDecodeError> {
        let value = self
            .params
            .get(name)
            .ok_or_else(|| RouteDecodeError::MissingParameter(name.into()))?;

        T::parse_param(value).map_err(|reason| RouteDecodeError::InvalidParameter {
            name: name.into(),
            reason,
        })
    }
}

fn placeholder(segment: &str) -> Option<&str> {
    segment.strip_prefix('{')?.strip_suffix('}')
}

fn decode_component(value: &str, query: bool) -> Result<String, RouteDecodeError> {
    let bytes = value.as_bytes();

    for (index, byte) in bytes.iter().enumerate() {
        if *byte == b'%'
            && (index + 2 >= bytes.len()
                || !bytes[index + 1].is_ascii_hexdigit()
                || !bytes[index + 2].is_ascii_hexdigit())
        {
            return Err(RouteDecodeError::InvalidUri(
                "malformed percent encoding".into(),
            ));
        }
    }

    let value = if query {
        value.replace('+', " ")
    } else {
        value.into()
    };

    percent_decode_str(&value)
        .decode_utf8()
        .map(String::from)
        .map_err(|_| RouteDecodeError::InvalidUri("parameter is not UTF-8".into()))
}

/// Formats a validated owned address without requiring its Rust destination type.
///
/// # Errors
/// Returns [`RouteDecodeError`] for unknown routes, invalid parameter sets,
/// or empty/dot-segment path parameters.
pub fn address_uri(
    address: &RouteAddress,
    descriptors: &[RouteDescriptor],
) -> Result<String, RouteDecodeError> {
    let descriptor = descriptors
        .iter()
        .find(|route| route.id == address.route)
        .ok_or_else(|| RouteDecodeError::UnknownRoute(address.route.clone()))?;

    address.validate(descriptor)?;
    let mut path_names = Vec::new();
    let mut segments = Vec::new();

    for segment in descriptor.path.split('/') {
        if let Some(name) = placeholder(segment) {
            let value = address
                .params
                .get(name)
                .ok_or_else(|| RouteDecodeError::MissingParameter(name.into()))?;

            if value.is_empty() || matches!(value.as_str(), "." | "..") {
                return Err(RouteDecodeError::InvalidUri(
                    "path parameters cannot be empty or dot segments".into(),
                ));
            }

            path_names.push(name);
            segments.push(utf8_percent_encode(value, NON_ALPHANUMERIC).to_string());
        } else {
            segments.push(segment.into());
        }
    }

    let mut uri = segments.join("/");

    let query: Vec<_> = address
        .params
        .iter()
        .filter(|(name, _)| !path_names.contains(&name.as_str()))
        .map(|(name, value)| (name.as_str(), value.as_str()))
        .collect();

    if !query.is_empty() {
        uri.push('?');
        uri.push_str(
            &url::form_urlencoded::Serializer::new(String::new())
                .extend_pairs(query)
                .finish(),
        );
    }

    Ok(uri)
}

/// Decodes a URI into a schema-validated address. Static paths take precedence.
///
/// # Errors
/// Returns [`RouteDecodeError`] for malformed/ambiguous URIs or a path that
/// does not match any descriptor.
pub fn uri_address(
    uri: &str,
    descriptors: &[RouteDescriptor],
) -> Result<RouteAddress, RouteDecodeError> {
    if !uri.starts_with('/') || uri.starts_with("//") || uri.contains('#') || uri.contains('\\') {
        return Err(RouteDecodeError::InvalidUri(
            "expected an absolute application path and query".into(),
        ));
    }

    let (path, query) = uri.split_once('?').unwrap_or((uri, ""));

    let segments: Vec<_> = path
        .split('/')
        .map(|value| decode_component(value, false))
        .collect::<Result<_, _>>()?;

    let mut descriptors: Vec<_> = descriptors.iter().collect();

    descriptors.sort_by_key(|route| {
        route
            .path
            .split('/')
            .filter(|segment| placeholder(segment).is_some())
            .count()
    });

    let mut best_specificity = None;
    let mut best_matches = Vec::new();

    for descriptor in descriptors {
        let pattern: Vec<_> = descriptor.path.split('/').collect();

        let specificity = pattern
            .iter()
            .filter(|segment| placeholder(segment).is_some())
            .count();

        if pattern.len() != segments.len()
            || !pattern
                .iter()
                .zip(&segments)
                .all(|(pattern, segment)| placeholder(pattern).is_some() || pattern == segment)
        {
            continue;
        }

        if best_specificity.is_some_and(|best| specificity > best) {
            break;
        }

        if best_specificity != Some(specificity) {
            best_specificity = Some(specificity);
            best_matches.clear();
        }

        let candidate = (|| {
            let mut address = RouteAddress {
                route: descriptor.id.into(),
                params: BTreeMap::new(),
            };

            for (pattern, segment) in pattern.iter().zip(&segments) {
                if let Some(name) = placeholder(pattern) {
                    address.params.insert(name.into(), segment.clone());
                }
            }

            for pair in query.split('&').filter(|pair| !pair.is_empty()) {
                let (name, value) = pair.split_once('=').unwrap_or((pair, ""));
                let name = decode_component(name, true)?;

                if address
                    .params
                    .insert(name.clone(), decode_component(value, true)?)
                    .is_some()
                {
                    return Err(RouteDecodeError::DuplicateParameter(name));
                }
            }

            address.validate(descriptor)?;
            address_uri(&address, &[*descriptor])?;

            Ok(address)
        })();

        best_matches.push(candidate);
    }

    let mut valid = Vec::new();
    let mut first_error = None;

    for candidate in best_matches {
        match candidate {
            Ok(address) => valid.push(address),
            Err(error) if first_error.is_none() => first_error = Some(error),
            Err(_) => {}
        }
    }

    match valid.as_slice() {
        [address] => Ok(address.clone()),
        [] => Err(first_error.unwrap_or_else(|| RouteDecodeError::UnknownRoute(path.into()))),
        _ => Err(RouteDecodeError::InvalidUri(
            "ambiguous route URI: multiple equally specific patterns match".into(),
        )),
    }
}

#[cfg(test)]
mod tests {
    use super::{ParameterDescriptor, RouteDecodeError, RouteDescriptor, uri_address};

    const FILE_PARAMS: &[ParameterDescriptor] = &[ParameterDescriptor {
        name: "id",
        value_type: "String",
        required: true,
    }];

    const SECTION_PARAMS: &[ParameterDescriptor] = &[ParameterDescriptor {
        name: "section",
        value_type: "String",
        required: true,
    }];

    #[test]
    fn rejects_equal_specificity_crossing_patterns() {
        let descriptors = [
            RouteDescriptor {
                id: "file",
                path: "/files/{id}",
                params: FILE_PARAMS,
            },
            RouteDescriptor {
                id: "settings",
                path: "/{section}/settings",
                params: SECTION_PARAMS,
            },
        ];

        assert!(matches!(
            uri_address("/files/settings", &descriptors),
            Err(RouteDecodeError::InvalidUri(message)) if message.contains("ambiguous")
        ));
    }

    #[test]
    fn preserves_static_precedence_over_dynamic_pattern() {
        let descriptors = [
            RouteDescriptor {
                id: "dynamic",
                path: "/files/{id}",
                params: FILE_PARAMS,
            },
            RouteDescriptor {
                id: "settings",
                path: "/files/settings",
                params: &[],
            },
        ];

        let address = uri_address("/files/settings", &descriptors).expect("static route");

        assert_eq!(address.route, "settings");
    }
}
