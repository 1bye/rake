//! Generate the committed skill and rule documentation from one catalogue.

use std::fmt::Write;

use super::catalogue::RULES;

pub(super) fn rules() -> String {
    let mut output = String::from("| Stable ID | Default | Check |\n| --- | --- | --- |\n");
    for rule in RULES {
        writeln!(
            output,
            "| `{}` | {} | {} |",
            rule.id,
            rule.level.name(),
            rule.message
        )
        .unwrap();
    }
    output
}

pub(crate) fn generate() -> String {
    let mut output = String::from(
        "---\nname: rake-gpui\ndescription: Write and check Rake view markup with the stable syntax lint rules.\n---\n\n# Rake syntax lint guide\n\nGenerated by `rake lint --guide`; edit the rule catalogue, then regenerate.\nUse `rake lint --guide=agents` for the compact AGENTS.md block; refresh an existing\nmarked block with `rake lint --guide=agents --update AGENTS.md`.\n\nAfter editing Rust or view! markup, run rake format, then rake lint.\nUse `rake lint --fix` for machine-safe edits and `rake format --check` in CI.\nA reasoned `// rake-lint: allow(ID) reason` suppresses a Rust finding;\nuse `# rake-lint: allow(ID) reason` in Cargo.toml.\nFor one intentional decision throughout a file, use a standalone\n`// rake-lint: allow-file(ID) reason` in the file header, before code\n(or `# rake-lint: allow-file(ID) reason` before TOML entries).\nThe reason is required. File scope covers only that rule in that file;\nunused, duplicate or misplaced file directives report invalid-suppression.\nUse a line suppression for a local exception.\nConfigure rust-analyzer with:\n\n```toml\n[rustfmt]\noverrideCommand = [\"rake\", \"format\", \"--stdin\"]\n```\n\nSee docs/format.md and docs/lint.md for command and configuration details.\nThis guide covers syntax only; it does not establish type-aware GPUI correctness.\n\n",
    );
    output.push_str(&rules());
    for rule in RULES {
        writeln!(output, "\n## {} ({})\n\n{}\n\n{}\n\nWhat to write instead: {}\n\nBefore:\n\n```text\n{}\n```\n\nAfter:\n\n```text\n{}\n```", rule.id, rule.level.name(), rule.message, rule.explanation, rule.fix, rule.before, rule.after).unwrap();
    }
    output
}

pub(super) const BEGIN: &str = "<!-- rake-lint:begin -->";
pub(super) const END: &str = "<!-- rake-lint:end -->";

/// Compact instructions shared by the committed block and scaffold template.
pub(crate) fn agents() -> String {
    let mut output = format!(
        "{BEGIN}\n## Rake agent rules\n\nAfter editing, run `rake format` then `rake lint`.\nUse `rake lint --fix` for machine-safe fixes.\n\n"
    );
    for summary in RULES.iter().filter_map(|rule| rule.agent_summary) {
        writeln!(output, "- {summary}").unwrap();
    }
    writeln!(
        output,
        "\nFull guide: `.agents/skills/rake-gpui/SKILL.md` (`rake lint --guide`).\n{END}"
    )
    .unwrap();
    output
}

/// Refresh only the marked contents; ambiguous or missing markers are an error.
pub(super) fn refresh_agents(text: &str) -> super::Result<String> {
    if text.matches(BEGIN).count() != 1 || text.matches(END).count() != 1 {
        return Err("expected exactly one rake-lint begin/end marker pair; copy rake lint --guide=agents first".into());
    }
    let start = text.find(BEGIN).expect("counted marker");
    let end = text.find(END).expect("counted marker");
    let line_end =
        |rest: &str| rest.is_empty() || rest.starts_with('\n') || rest.starts_with("\r\n");
    if end < start
        || (start > 0 && !text[..start].ends_with('\n'))
        || (end > 0 && !text[..end].ends_with('\n'))
        || !line_end(&text[start + BEGIN.len()..])
        || !line_end(&text[end + END.len()..])
    {
        return Err("rake-lint markers must be ordered, standalone lines".into());
    }
    let newline = if text[start + BEGIN.len()..].starts_with("\r\n") {
        "\r\n"
    } else {
        "\n"
    };
    let block = agents();
    let contents = block
        .strip_prefix(BEGIN)
        .expect("generated begin")
        .strip_suffix(&format!("{END}\n"))
        .expect("generated end")
        .replace('\n', newline);
    Ok(format!(
        "{}{}{}",
        &text[..start + BEGIN.len()],
        contents,
        &text[end..]
    ))
}
