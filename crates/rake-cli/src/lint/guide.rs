//! Generate the committed skill and rule documentation from one catalogue.

use std::fmt::Write;

use super::catalogue::RULES;

pub(super) fn rules() -> String {
    let mut output = String::from("| Stable ID | Default | Check |\n| --- | --- | --- |\n");
    for rule in RULES {
        writeln!(
            output,
            "| `{}` | {} | {} |",
            rule.id,
            rule.level.name(),
            rule.message
        )
        .unwrap();
    }
    output
}

pub(super) fn generate() -> String {
    let mut output = String::from(
        "---\nname: rake-gpui\ndescription: Write and check Rake view markup with the stable syntax lint rules.\n---\n\n# Rake syntax lint guide\n\nGenerated by `rake lint --guide`; edit the rule catalogue, then regenerate.\n\nAfter editing Rust or view! markup, run rake format, then rake lint.\nUse `rake lint --fix` for machine-safe edits and `rake format --check` in CI.\nA reasoned `// rake-lint: allow(ID) reason` suppresses a Rust finding;\nuse `# rake-lint: allow(ID) reason` in Cargo.toml.\nConfigure rust-analyzer with:\n\n```toml\n[rustfmt]\noverrideCommand = [\"rake\", \"format\", \"--stdin\"]\n```\n\nSee docs/format.md and docs/lint.md for command and configuration details.\nThis guide covers syntax only; it does not establish type-aware GPUI correctness.\n\n",
    );
    output.push_str(&rules());
    for rule in RULES {
        writeln!(output, "\n## {} ({})\n\n{}\n\n{}\n\nWhat to write instead: {}\n\nBefore:\n\n```text\n{}\n```\n\nAfter:\n\n```text\n{}\n```", rule.id, rule.level.name(), rule.message, rule.explanation, rule.fix, rule.before, rule.after).unwrap();
    }
    output
}
