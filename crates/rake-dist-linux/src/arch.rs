//! Arch packages are built by makepkg from an inspectable, checksummed recipe.
use crate::{Error, run, shell};
use sha2::{Digest, Sha256};
use std::{
    fs,
    path::{Path, PathBuf},
    process::Command,
};

/// Inputs for a binary Arch package; `payload` mirrors the installed filesystem.
#[derive(Debug)]
pub struct ArchPackage<'a> {
    /// Validated package name.
    pub name: &'a str,
    /// Explicit Arch-compatible upstream version.
    pub version: &'a str,
    /// Rust target triple.
    pub target: &'a str,
    /// Human-readable application name.
    pub display_name: &'a str,
    /// Native pacman dependency expressions.
    pub dependencies: &'a [String],
    /// Root containing usr/bin, usr/lib and usr/share.
    pub payload: &'a Path,
    /// Dedicated empty recipe/build directory.
    pub output: &'a Path,
}

/// Generates PKGBUILD/.SRCINFO and builds using the native user's makepkg policy.
/// # Errors
/// Returns invalid package metadata, filesystem or makepkg diagnostics. Requires a
/// non-root Arch runner; it never installs dependencies or changes pacman settings.
pub fn build_arch(input: &ArchPackage<'_>) -> Result<Vec<PathBuf>, Error> {
    let architecture = match input.target.split('-').next() {
        Some("x86_64") => "x86_64",
        Some("aarch64") => "aarch64",
        _ => return Err(Error::Metadata("unsupported Arch architecture".into())),
    };
    if input.version.is_empty() || input.version.contains(['-', '/', '\n', '\r']) {
        return Err(Error::Metadata(
            "Arch package_version must exclude release separators".into(),
        ));
    }
    fs::create_dir_all(input.output)?;
    let archive_path = input.output.join("payload.tar.gz");
    let encoder = flate2::write::GzEncoder::new(
        fs::File::create(&archive_path)?,
        flate2::Compression::default(),
    );
    let mut archive = tar::Builder::new(encoder);
    archive.follow_symlinks(false);
    archive.append_dir_all(".", input.payload)?;
    archive.into_inner()?.finish()?;
    let mut file = fs::File::open(&archive_path)?;
    let mut hash = Sha256::new();
    std::io::copy(&mut file, &mut hash)?;
    let checksum = format!("{:x}", hash.finalize());
    let dependencies = input
        .dependencies
        .iter()
        .map(|value| shell(value))
        .collect::<Vec<_>>()
        .join(" ");
    let recipe = format!(
        "# Generated by Rake. Review before repository publication.\npkgname={}\npkgver={}\npkgrel=1\npkgdesc={}\narch=({architecture})\ndepends=({dependencies})\noptions=('!strip' '!debug')\nsource=('payload.tar.gz')\nsha256sums=('{checksum}')\npackage() {{\n  cp -a -- \"$srcdir/usr\" \"$pkgdir/usr\"\n}}\n",
        shell(input.name),
        shell(input.version),
        shell(input.display_name)
    );
    fs::write(input.output.join("PKGBUILD"), recipe)?;
    let source_info = run(Command::new("makepkg")
        .current_dir(input.output)
        .arg("--printsrcinfo"))?;
    fs::write(input.output.join(".SRCINFO"), source_info)?;
    run(Command::new("makepkg").current_dir(input.output).args([
        "--force",
        "--nodeps",
        "--noconfirm",
    ]))?;
    let mut output = vec![
        input.output.join("PKGBUILD"),
        input.output.join(".SRCINFO"),
        archive_path,
    ];
    let packages = fs::read_dir(input.output)?
        .filter_map(Result::ok)
        .map(|entry| entry.path())
        .filter(|path| {
            path.file_name()
                .is_some_and(|name| name.to_string_lossy().contains(".pkg.tar."))
        })
        .collect::<Vec<_>>();
    if packages.is_empty() {
        return Err(Error::Metadata("makepkg produced no package".into()));
    }
    output.extend(packages);
    Ok(output)
}

